const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const variant = process.argv[2];
const folders = { original: 'lab08-auth', local: 'lab08-auth-local' };
if (!Object.hasOwn(folders, variant)) throw new Error('Choose original or local');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'labs', folders[variant]);
const evidence = path.join(root, 'docs', 'evidence', variant);
fs.mkdirSync(evidence, { recursive: true });
const config = { rootDir: dir, cacheDirectory: path.join(dir, 'node_modules', '.cache', 'jest'), testEnvironment: 'node', collectCoverageFrom: ['app.js', 'services/**/*.js'], coverageReporters: ['text', 'html', 'json-summary'] };
const args = [path.join(dir, 'node_modules', 'jest', 'bin', 'jest.js'), '--config', JSON.stringify(config), '--runInBand', '--coverage', '--json', '--outputFile', path.join(evidence, 'test-results.json')];
const run = spawnSync(process.execPath, args, { cwd: dir, encoding: 'utf8' });
const log = (run.stdout || '') + (run.stderr || '');
process.stdout.write(log);
fs.writeFileSync(path.join(evidence, 'test-run.txt'), log.replace(/[ \t]+$/gm, ''));
if (run.error) throw run.error;
if (run.status !== 0) process.exit(run.status || 1);
fs.copyFileSync(path.join(dir, 'coverage', 'coverage-summary.json'), path.join(evidence, 'coverage-summary.json'));
const crypto = require('crypto');
const files = ['app.js', 'services/authService.js', 'package.json', 'package-lock.json', variant === 'original' ? 'test/auth.test.js' : 'tests/auth.test.js'];
const hashes = Object.fromEntries(files.map(f => [f, crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, f))).digest('hex')]));
fs.writeFileSync(path.join(evidence, 'provenance.json'), JSON.stringify({variant, measuredAt: new Date().toISOString(), node: process.version, sourceCommit: variant === 'original' ? 'a0354412f65fbe20c53bcc91b3ed5a7b4ba15290' : null, sourceDescription: variant === 'original' ? 'Member module, source files preserved' : 'CNPMTH local module described in the report', hashes}, null, 2) + '\n');
